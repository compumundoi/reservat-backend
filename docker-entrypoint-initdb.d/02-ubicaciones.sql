-- ============================================
-- BACKFILL DE LOS REGISTROS EXISTENTES
-- ============================================
-- El texto libre historico se resuelve contra el catalogo ignorando
-- tildes, mayusculas y espacios. Lo que no matchea queda con los ids
-- en NULL y el texto intacto: se corrige al editar el registro.

CREATE OR REPLACE FUNCTION usr_app.slug_ubicacion(valor text)
RETURNS text
LANGUAGE sql IMMUTABLE
AS $$ SELECT lower(unaccent(btrim(coalesce(valor, '')))) $$;

DO $$
DECLARE
    tabla text;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['proveedores', 'servicios', 'mayoristas'] LOOP
        EXECUTE format($f$
            UPDATE usr_app.%1$I AS t
            SET municipio_id    = m.id,
                departamento_id = d.id,
                pais_id         = d.country_id,
                ciudad          = m.name,
                departamento    = d.name,
                pais            = c.name
            FROM usr_app.municipalities m
            JOIN usr_app.departments d ON d.id = m.department_id
            JOIN usr_app.countries   c ON c.id = d.country_id
            WHERE t.municipio_id IS NULL
              AND usr_app.slug_ubicacion(t.ciudad) = usr_app.slug_ubicacion(m.name)
        $f$, tabla);
    END LOOP;
END $$;

-- Todo lo que quedo sin resolver es colombiano por defecto.
UPDATE proveedores SET pais_id = 46, pais = 'Colombia' WHERE pais_id IS NULL;
UPDATE servicios   SET pais_id = 46, pais = 'Colombia' WHERE pais_id IS NULL;
UPDATE mayoristas  SET pais_id = 46, pais = 'Colombia' WHERE pais_id IS NULL;

-- Segunda pasada: el catalogo nombra algunas ciudades con su forma larga
-- ("Bogota" -> "Bogota, D.c.", "Cartagena" -> "Cartagena De Indias").
-- Solo se aplica cuando el prefijo resuelve a un unico municipio.
DO $$
DECLARE
    tabla text;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['proveedores', 'servicios', 'mayoristas'] LOOP
        EXECUTE format($f$
            UPDATE usr_app.%1$I AS t
            SET municipio_id    = u.municipio_id,
                departamento_id = u.departamento_id,
                pais_id         = u.country_id,
                ciudad          = u.municipio,
                departamento    = u.departamento,
                pais            = u.pais
            FROM (
                SELECT t2.ctid AS fila,
                       min(m.id)          AS municipio_id,
                       min(d.id)          AS departamento_id,
                       min(d.country_id)  AS country_id,
                       min(m.name)        AS municipio,
                       min(d.name)        AS departamento,
                       min(c.name)        AS pais
                FROM usr_app.%1$I t2
                JOIN usr_app.municipalities m
                  ON usr_app.slug_ubicacion(m.name) LIKE usr_app.slug_ubicacion(t2.ciudad) || ' %%'
                  OR usr_app.slug_ubicacion(m.name) LIKE usr_app.slug_ubicacion(t2.ciudad) || ',%%'
                JOIN usr_app.departments d ON d.id = m.department_id
                JOIN usr_app.countries   c ON c.id = d.country_id
                WHERE t2.municipio_id IS NULL
                  AND btrim(coalesce(t2.ciudad, '')) <> ''
                GROUP BY t2.ctid
                HAVING count(*) = 1
            ) u
            WHERE t.ctid = u.fila
        $f$, tabla);
    END LOOP;
END $$;

-- Tercera pasada: cuando el prefijo es ambiguo ("Cartagena" existe en
-- Bolivar y en Caqueta) se desempata con el departamento ya cargado.
DO $$
DECLARE
    tabla text;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['proveedores', 'servicios', 'mayoristas'] LOOP
        EXECUTE format($f$
            UPDATE usr_app.%1$I AS t
            SET municipio_id    = u.municipio_id,
                departamento_id = u.departamento_id,
                pais_id         = u.country_id,
                ciudad          = u.municipio,
                departamento    = u.departamento,
                pais            = u.pais
            FROM (
                SELECT t2.ctid AS fila,
                       min(m.id)         AS municipio_id,
                       min(d.id)         AS departamento_id,
                       min(d.country_id) AS country_id,
                       min(m.name)       AS municipio,
                       min(d.name)       AS departamento,
                       min(c.name)       AS pais
                FROM usr_app.%1$I t2
                JOIN usr_app.departments d
                  ON usr_app.slug_ubicacion(d.name) = usr_app.slug_ubicacion(t2.departamento)
                JOIN usr_app.municipalities m
                  ON m.department_id = d.id
                 AND (usr_app.slug_ubicacion(m.name) = usr_app.slug_ubicacion(t2.ciudad)
                      OR usr_app.slug_ubicacion(m.name) LIKE usr_app.slug_ubicacion(t2.ciudad) || ' %%'
                      OR usr_app.slug_ubicacion(m.name) LIKE usr_app.slug_ubicacion(t2.ciudad) || ',%%')
                JOIN usr_app.countries c ON c.id = d.country_id
                WHERE t2.municipio_id IS NULL
                  AND btrim(coalesce(t2.ciudad, '')) <> ''
                GROUP BY t2.ctid
                HAVING count(*) = 1
            ) u
            WHERE t.ctid = u.fila
        $f$, tabla);
    END LOOP;
END $$;
