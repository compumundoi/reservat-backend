-- ============================================================
-- Catalogo de ubicaciones (paises / departamentos / municipios)
-- y normalizacion de los campos de ubicacion de las tablas de
-- negocio (proveedores, servicios, mayoristas).
--
-- Los ids del catalogo son la fuente de verdad. Las columnas de
-- texto (pais, departamento, ciudad) se mantienen sincronizadas
-- porque el buscador del landing, el MCP y los listados siguen
-- leyendo el nombre en texto.
-- ============================================================

SET search_path TO usr_app, public;

CREATE EXTENSION IF NOT EXISTS unaccent;

-- ============================================
-- TABLAS DEL CATALOGO
-- ============================================

CREATE TABLE IF NOT EXISTS countries (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    code character varying(2) NOT NULL,
    created_at timestamp without time zone DEFAULT now(),
    updated_at timestamp without time zone DEFAULT now(),
    CONSTRAINT countries_code_key UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS departments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id integer NOT NULL REFERENCES countries(id) ON DELETE CASCADE,
    name text NOT NULL,
    code character varying(5) NOT NULL,
    created_at timestamp without time zone DEFAULT now(),
    updated_at timestamp without time zone DEFAULT now(),
    CONSTRAINT departments_country_code_key UNIQUE (country_id, code)
);

CREATE TABLE IF NOT EXISTS municipalities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id integer NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    name text NOT NULL,
    code character varying(8) NOT NULL,
    created_at timestamp without time zone DEFAULT now(),
    updated_at timestamp without time zone DEFAULT now(),
    CONSTRAINT municipalities_code_key UNIQUE (code)
);

CREATE INDEX IF NOT EXISTS idx_departments_country ON departments USING btree (country_id);
CREATE INDEX IF NOT EXISTS idx_municipalities_department ON municipalities USING btree (department_id);

